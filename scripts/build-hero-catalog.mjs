/*
 * Builds the sample catalog the homepage hero matches against.
 *
 * The marketing site is static, so we bake a trimmed, public-safe snapshot of
 * the food_item catalog into assets/data/hero-catalog.js at build time rather
 * than calling the API from the browser. That keeps the hero rendering before
 * first paint (no flicker, no CORS, no dependency on backend uptime) and keeps
 * credentials out of the client.
 *
 * Usage:
 *   node scripts/build-hero-catalog.mjs --from ../nutrics/backend/data/nutrics.food_item.json
 *   MONGODB_URI=... MONGODB_DB=nutrics node scripts/build-hero-catalog.mjs
 *
 * Re-run whenever the catalog changes; commit the generated file.
 */
import { writeFileSync, readFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = resolve(ROOT, "assets/data/hero-catalog.js");

// How many items to keep per tag. The hero only ever shows three meals; this
// is about variety across loads, traded off against page weight.
const PER_TAG = 12;

// Which meal slots each catalog tag can fill.
// No catalog variant exceeds ~472 kcal, so a 2,000+ kcal day is built from
// more meals rather than bigger portions — hence the snack slot.
const SLOTS = {
  Breakfast: ["breakfast"],
  Salad: ["lunch", "snack"],
  Soup: ["lunch", "snack"],
  Dessert: ["snack"],
  Chicken: ["lunch", "dinner"],
  Seafood: ["lunch", "dinner"],
  Vegetarian: ["lunch", "dinner"],
  Vegan: ["lunch", "dinner"],
  Beef: ["dinner"],
};

const ICONS = {
  Breakfast: "fa-mug-hot",
  Chicken: "fa-drumstick-bite",
  Beef: "fa-utensils",
  Seafood: "fa-fish",
  Vegetarian: "fa-leaf",
  Vegan: "fa-seedling",
  Salad: "fa-leaf",
  Soup: "fa-bowl-food",
  Dessert: "fa-mug-hot",
};

function arg(name) {
  const i = process.argv.indexOf(name);
  return i > -1 ? process.argv[i + 1] : null;
}

async function loadItems() {
  const file = arg("--from");
  if (file) {
    const raw = JSON.parse(readFileSync(resolve(process.cwd(), file), "utf8"));
    return { items: raw, source: `file:${file}` };
  }

  const uri = process.env.MONGODB_URI;
  if (!uri) {
    throw new Error(
      "Pass --from <food_item.json> or set MONGODB_URI (with optional MONGODB_DB)."
    );
  }

  let mongodb;
  try {
    mongodb = await import("mongodb");
  } catch {
    throw new Error(
      "MONGODB_URI is set but the 'mongodb' driver is not installed here.\n" +
        "This site has no dependencies by design — either run this script from\n" +
        "the backend repo, or export the collection and use --from."
    );
  }

  const client = new mongodb.MongoClient(uri);
  await client.connect();
  try {
    const db = client.db(process.env.MONGODB_DB || undefined);
    const items = await db.collection("food_item").find({}).toArray();
    return { items, source: "mongodb" };
  } finally {
    await client.close();
  }
}

function normalize(item) {
  const tag = item.tag;
  const slots = SLOTS[tag];
  if (!slots) return null;

  const variants = {};
  for (const [name, size] of Object.entries(item.availableSizes || {})) {
    const m = size?.macros;
    if (!m || !m.calories) continue;
    // [kcal, protein, carbs, fat] — arrays keep the generated file small.
    variants[name] = [
      Math.round(m.calories),
      Math.round(m.proteins),
      Math.round(m.carbs),
      Math.round(m.fats),
    ];
  }
  if (!Object.keys(variants).length) return null;

  return {
    n: String(item.title || "").trim(),
    k: String(item.vendor_name || "").trim(),
    t: tag,
    i: ICONS[tag] || "fa-utensils",
    s: slots,
    p: tag === "Vegan" ? 1 : 0,
    v: variants,
  };
}

const { items, source } = await loadItems();

const byTag = new Map();
for (const raw of items) {
  const item = normalize(raw);
  if (!item) continue;
  const bucket = byTag.get(item.t) || [];
  bucket.push(item);
  byTag.set(item.t, bucket);
}

// Prefer items carrying the most variants — they give the matcher more room.
const kept = [];
for (const [, bucket] of byTag) {
  bucket.sort(
    (a, b) => Object.keys(b.v).length - Object.keys(a.v).length
  );
  kept.push(...bucket.slice(0, PER_TAG));
}

const payload = {
  generatedAt: new Date().toISOString().slice(0, 10),
  source,
  totals: {
    items: items.length,
    kitchens: new Set(items.map((i) => i.vendor_name).filter(Boolean)).size,
    tags: byTag.size,
  },
  items: kept,
};

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  "/* Generated by scripts/build-hero-catalog.mjs — do not edit by hand. */\n" +
    "window.NUTRICS_CATALOG = " +
    JSON.stringify(payload) +
    ";\n"
);

console.log(
  `Wrote ${OUT}\n  ${kept.length} items from ${payload.totals.items} (` +
    `${payload.totals.kitchens} kitchens, ${payload.totals.tags} tags)`
);
